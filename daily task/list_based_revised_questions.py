"""Q51. Find All Prime Numbers in a List

Test Cases:

Input: [1, 2, 3, 4, 5, 6] → Output: [2, 3, 5]

 Input: [10, 11, 12, 13] → Output: [11, 13]

 Input: [4, 6, 8] → Output: []

"""

lst = eval(input("Enter list: "))
result = []
i = 0
while i < len(lst):
    num = lst[i]

    if num > 1:
        is_prime = True
        divisor = 2
        while divisor * divisor <= num:
            if num % divisor == 0:
                is_prime = False
            divisor += 1

        if is_prime:
            result.append(num)
    i += 1
print("Output:", result)

